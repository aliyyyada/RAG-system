"""Синтетический закупочный пакет для тестов: 7 DOCX-файлов с выдуманными данными.

Структура повторяет настоящий пакет (договор, ТЗ, записка, расчёт НМЦ, запрос КП, два-три КП),
но все названия, ИНН и суммы вымышлены. Параметры позволяют «испортить» пакет: арифметика,
число КП, расхождения ТЗ и записки.
"""

from __future__ import annotations

from pathlib import Path

from docx import Document

SUPPLIERS = [
    ("ООО «Поставщик Один»", "7701234567", "770101001"),
    ("ООО «Поставщик Два»", "7702345678", "770201001"),
    ("ООО «Поставщик Три»", "7703456789", "770301001"),
]


def _save(path: Path, paragraphs: list[str], tables: list[list[list[str]]] | None = None) -> Path:
    d = Document()
    for p in paragraphs:
        d.add_paragraph(p)
    for rows in tables or []:
        t = d.add_table(rows=len(rows), cols=len(rows[0]))
        for i, row in enumerate(rows):
            for j, v in enumerate(row):
                t.cell(i, j).text = v
        d.add_paragraph("")
    d.save(str(path))
    return path


def make_tz(path: Path, *, qty: str = "10", code: str = "26.20.11.110") -> Path:
    return _save(
        path,
        [
            "Техническое задание на поставку ноутбуков",
            f"Код ОКПД2: {code}",
            "Требования к продукции и характеристики: масса не более 2 кг, толщина не более 20 мм, "
            "мощность блока питания 65 Вт, гарантия 36 мес.",
            "Количество: " + qty + " шт.",
            "Срок поставки: в течение 30 дней с даты заключения договора.",
            "Место поставки: г. Москва, ул. Тестовая, д. 1.",
        ],
        [[["Наименование", "Ед. изм.", "Количество"], ["Ноутбук", "шт", qty]]],
    )


def make_note(path: Path, *, qty: str = "10") -> Path:
    return _save(
        path,
        [
            "Сопроводительная записка к заявке на приобретение",
            "Прошу приобрести ноутбуки в соответствии с техническим заданием. Код ОКПД2: 26.20.11.110.",
        ],
        [[["Наименование", "Ед. изм.", "Количество"], ["Ноутбук", "шт", qty]]],
    )


def make_contract(path: Path, *, price: str = "600 000,00", pay_days: int = 7) -> Path:
    name, inn, _ = SUPPLIERS[0]
    return _save(
        path,
        [
            "Договор поставки № 15 от 10.11.2026",
            f"{name}, ИНН {inn}, именуемое Поставщик, и ООО «Покупатель», именуемое Покупатель.",
            "1. Предмет договора",
            "Поставщик обязуется поставить ноутбуки (ОКПД2 26.20.11.110), а Покупатель принять и оплатить товар.",
            f"Цена договора: {price} руб., в том числе НДС.",
            f"Оплата производится безналичным расчётом платёжным поручением на основании счёта в течение {pay_days} "
            "(семи) рабочих дней после приёмки товара.",
            "Транспортно-заготовительные расходы включены в цену договора.",
            "Срок поставки: 30 дней с даты заключения договора. Место поставки: г. Москва, ул. Тестовая, д. 1. "
            "Приёмка товара осуществляется по товарной накладной.",
            "Срок действия договора: до 31.12.2026.",
        ],
    )


def make_request(path: Path) -> Path:
    return _save(
        path,
        [
            "Запрос о предоставлении информации о ценах",
            "Прошу направить коммерческое предложение на поставку ноутбуков.",
            "Требования к продукции: см. техническое задание. Место поставки: г. Москва. Срок поставки: 30 дней. "
            "Условия оплаты: в течение 7 рабочих дней.",
            "Срок предоставления информации: не позднее 10.11.2026, цена каждой единицы продукции обязательна.",
            "Проведение сбора информации не влечёт возникновения обязательств заказчика.",
            "Допуски и лицензии не требуются.",
            "Адресаты: ООО «Поставщик Один», ООО «Поставщик Два», ООО «Поставщик Три».",
        ],
    )


def make_kp(
    path: Path, n: int, *, price: str, total: str | None = None, line_total: str | None = None
) -> Path:
    name, inn, kpp = SUPPLIERS[n - 1]
    lt = line_total or total or price
    return _save(
        path,
        [
            f"Коммерческое предложение № {n} от 0{4 + n}.11.2026",
            f"{name}, ИНН {inn}, КПП {kpp}",
            "Предлагаем поставить ноутбуки: масса не более 2 кг, толщина не более 20 мм, блок питания 65 Вт, гарантия 36 мес. "
            "Количество: 10 шт.",
            "Срок поставки: 30 дней. Оплата: в течение 7 рабочих дней.",
            f"Итого: {total or lt} руб. с НДС",
            "Подпись руководителя, М.П.",
        ],
        [
            [
                [
                    "Наименование",
                    "Ед. изм.",
                    "Кол-во",
                    "Цена за единицу, руб. с НДС",
                    "Сумма, руб. с НДС",
                ],
                ["Ноутбук", "шт", "10", price, lt],
            ]
        ],
    )


def make_nmc(
    path: Path, *, prices=("60000,00", "62000,00", "58000,00"), avg="60000,00", total="600000,00"
) -> Path:
    head = [
        "№ п/п",
        "Наименование",
        "Ед.изм.",
        "Кол-во в ед.изм.",
        "Ставка НДС, %",
        "Предложение №1",
        "Предложение №2",
        "Предложение №3",
        "Средняя арифметическая цена за ед.изм.",
        "Общая стоимость, руб. с НДС",
    ]
    return _save(
        path,
        [
            "Расчет НМЦ методом сопоставимых рыночных цен (анализа рынка)",
            "Основные требования к продукции: ноутбуки по техническому заданию.",
            "Место поставки: г. Москва. Срок начала и окончания исполнения договора: 30 дней.",
            "Условия оплаты: 7 рабочих дней. Порядок определения поставщиков: запрос цен.",
            "Перечень поставщиков, предоставивших ценовые предложения: три организации.",
            f"Рассчитанная величина НМЦ: {total} руб.",
        ],
        [
            [
                head,
                ["1", "Ноутбук", "шт", "10", "20", *prices, avg, total],
                ["", "Итого", "", "", "", "", "", "", "", total],
            ]
        ],
    )


def make_package(folder: Path, **overrides: object) -> dict[str, Path]:
    """Хороший пакет. overrides: kp_count, nmc_total, nmc_avg, note_qty, contract_price, tz_code."""
    folder.mkdir(parents=True, exist_ok=True)
    kp_count = int(overrides.get("kp_count", 3))
    prices = ["60 000,00", "62 000,00", "58 000,00"]
    totals = ["600 000,00", "620 000,00", "580 000,00"]
    files: dict[str, Path] = {
        "1. Договорной документ.docx": make_contract(
            folder / "c.docx", price=str(overrides.get("contract_price", "600 000,00"))
        ),
        "2. Техническое задание.docx": make_tz(
            folder / "tz.docx", code=str(overrides.get("tz_code", "26.20.11.110"))
        ),
        "3. Сопроводительная записка к заявке на приобретение.docx": make_note(
            folder / "note.docx", qty=str(overrides.get("note_qty", "10"))
        ),
        "4. Расчет НМЦ.docx": make_nmc(
            folder / "nmc.docx",
            total=str(overrides.get("nmc_total", "600000,00")),
            avg=str(overrides.get("nmc_avg", "60000,00")),
        ),
        "5. Запрос КП.docx": make_request(folder / "req.docx"),
    }
    for n in range(1, kp_count + 1):
        files[f"{5 + n}. Коммерческое предложение №{n}.docx"] = make_kp(
            folder / f"kp{n}.docx", n, price=prices[n - 1], total=totals[n - 1]
        )
    return files
