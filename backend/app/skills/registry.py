"""Реестр навыков (агентов).

Навык — будущий плагин, например «проверить папку документов на соответствие ЕПОЗ».
У каждого навыка своё право `skill.<имя>.use`: навык появляется в интерфейсе только у тех,
кому это право выдано. Сейчас здесь только каркас: описание навыков и их права.
Исполнение навыков появится на этапе 7.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class Skill:
    name: str  # латиница, цифры и _, используется в коде права
    title: str
    description: str
    available: bool = False  # False — навык объявлен, но ещё не реализован («скоро»)


SKILLS: tuple[Skill, ...] = (
    Skill(
        name="epoz_check",
        title="Проверка папки на соответствие ЕПОЗ",
        description="Проверяет папку документов на соответствие ЕПОЗ (см. open-questions #10).",
    ),
)
